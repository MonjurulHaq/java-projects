    private void InsertActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_InsertActionPerformed
        // TODO add your handling code here:
        if (uid.getText().isEmpty()
                || uname.getText().isEmpty()
                || uemail.getText().isEmpty()
                || uphone.getText().isEmpty()) {

            JOptionPane.showMessageDialog(this,
                    "All fields are required!",
                    "Validation Error",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }

        int userid;
        int phone;

        try {
            userid = Integer.parseInt(uid.getText());
            phone = Integer.parseInt(uphone.getText());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                    "User ID and Phone must be numbers!",
                    "Input Error",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }

        String name = uname.getText();
        String email = uemail.getText();

        try {
            Class.forName("com.mysql.cj.jdbc.Driver");
            Connection conn = DriverManager.getConnection(DB_URL, DB_USER, DB_PASS);

            String SQL = "INSERT INTO userinfo (userid, name, email, phone) VALUES (?, ?, ?, ?)";
            PreparedStatement pst = conn.prepareStatement(SQL);

            pst.setInt(1, userid);
            pst.setString(2, name);
            pst.setString(3, email);
            pst.setInt(4, phone);

            pst.executeUpdate();

            JOptionPane.showMessageDialog(this,
                    "User added successfully!",
                    "Success",
                    JOptionPane.INFORMATION_MESSAGE);

            pst.close();
            conn.close();

        } catch (SQLException se) {
            System.out.println("Error :" + se);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                    "Database Error: " + e.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
        }
        uid.setText("");
        uname.setText("");
        uemail.setText("");
        uphone.setText("");


    }//GEN-LAST:event_InsertActionPerformed

