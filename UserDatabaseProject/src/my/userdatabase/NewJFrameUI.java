    private void UpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_UpdateActionPerformed
        // TODO add your handling code here:
        if (uid.getText().isEmpty() || uname.getText().isEmpty()
                || uemail.getText().isEmpty() || uphone.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "All fields required!");
            return;
        }

        try {
            int id = Integer.parseInt(uid.getText());
            int phone = Integer.parseInt(uphone.getText());

            Connection con = DriverManager.getConnection(DB_URL, DB_USER, DB_PASS);

            PreparedStatement pst = con.prepareStatement("UPDATE userinfo SET name=?, email=?, phone=? WHERE userid=?");

            pst.setString(1, uname.getText());
            pst.setString(2, uemail.getText());
            pst.setInt(3, phone);
            pst.setInt(4, id);

            int x = pst.executeUpdate();

            JOptionPane.showMessageDialog(this, x > 0 ? "User Updated!" : "User Not Found!");
            uid.setText("");
            uname.setText("");
            uemail.setText("");
            uphone.setText("");

            pst.close();
            con.close();

        } catch (SQLException se) {
            System.out.println("Error :" + se);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_UpdateActionPerformed

    private void DeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DeleteActionPerformed
        // TODO add your handling code here:
        if (uid.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "User ID is required to delete!",
                    "Validation Error",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }

        int userid;

        try {
            userid = Integer.parseInt(uid.getText());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                    "User ID must be a valid number!",
                    "Input Error",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(
                this,
                "Are you sure you want to delete this user?",
                "Confirm Delete",
                JOptionPane.YES_NO_OPTION
        );

        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            Class.forName("com.mysql.cj.jdbc.Driver");
            Connection conn = DriverManager.getConnection(DB_URL, DB_USER, DB_PASS);
            String SQL = "DELETE FROM userinfo WHERE userid = ?";
            PreparedStatement pst = conn.prepareStatement(SQL);
            pst.setInt(1, userid);

            int rowsAffected = pst.executeUpdate();

            if (rowsAffected == 0) {
                JOptionPane.showMessageDialog(this,
                        "No user found with this ID!",
                        "Not Found",
                        JOptionPane.WARNING_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this,
                        "User deleted successfully!",
                        "Success",
                        JOptionPane.INFORMATION_MESSAGE);

                uid.setText("");
                uname.setText("");
                uemail.setText("");
                uphone.setText("");
            }

            pst.close();
            conn.close();

        } catch (SQLException se) {
            System.out.println("Error :" + se);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                    "Database Error: " + e.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_DeleteActionPerformed

    private void ViewActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ViewActionPerformed
        // TODO add your handling code here:
        if (uid.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Enter User ID!");
            return;
        }

        try {
            int id = Integer.parseInt(uid.getText());

            Connection con = DriverManager.getConnection(DB_URL, DB_USER, DB_PASS);

            PreparedStatement pst = con.prepareStatement(
                    "SELECT userid, name, email, phone FROM userinfo WHERE userid=?");

            pst.setInt(1, id);
            ResultSet rs = pst.executeQuery();

            if (rs.next()) {
                String msg = "User ID: " + rs.getString("userid")
                        + "\nName: " + rs.getString("name")
                        + "\nEmail: " + rs.getString("email")
                        + "\nPhone: " + rs.getString("phone");

                JOptionPane.showMessageDialog(this, msg, "User Details",
                        JOptionPane.INFORMATION_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this, "User Not Found!");
            }

            rs.close();
            pst.close();
            con.close();

        } catch (SQLException se) {
            System.out.println("Error :" + se);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_ViewActionPerformed

